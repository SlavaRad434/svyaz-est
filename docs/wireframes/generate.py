import textwrap

ROOT = Path(__file__).parent
SCREENS = []


class Screen:
    def __init__(self, key, title, note, width=360, height=760):
        self.key, self.title, self.note = key, title, note
        self.width, self.height = width, height
        self.parts = []
        self.rect(0, 0, width, height, '#fff')
        self.text(18, 30, 'СвязьЕсть', 18, True)
        self.text(width-74 if width == 360 else 200, 30, 'Демо', 12)
        self.line(0, 52, width, 52)
        self.text(18, 82, title, 20, True)
        SCREENS.append(self)

    def rect(self, x, y, w, h, fill='#fff', stroke='#999', radius=0):
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{fill}" stroke="{stroke}"/>')

    def line(self, x, y, xx, yy):
        self.parts.append(f'<path d="M{x} {y}L{xx} {yy}" stroke="#bbb" fill="none"/>')

    def text(self, x, y, value, size=14, bold=False, fill='#202020'):
        self.parts.append(f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{600 if bold else 400}" fill="{fill}">{escape(value)}</text>')

    def paragraph(self, y, value, width=38, x=18, size=14):
        lines = textwrap.wrap(value, width=width)
        for i, line in enumerate(lines):
            self.text(x, y+i*21, line, size)
        return y+len(lines)*21

    def button(self, y, label, target=None, primary=False, x=18, w=324, disabled=False):
        if disabled:
            self.rect(x, y, w, 46, '#eee', '#aaa', 5)
            self.text(x+14, y+29, label, 14, True, '#777')
            return
        if target:
            self.parts.append(f'<a href="#{target}" aria-label="{escape(label)}">')
        self.rect(x, y, w, 46, '#252525' if primary else '#fff', '#252525', 5)
        self.text(x+14, y+29, label, 14, True, '#fff' if primary else '#202020')
        if target:
            self.parts.append('</a>')

    def field(self, y, label, value):
        self.text(18, y, label, 12)
        self.rect(18, y+9, 324, 44, '#f8f8f8', '#999', 4)
        self.text(30, y+37, value)
        self.text(316, y+37, '⌄')

    def row(self, y, label, value):
        self.text(18, y, label, 13)
        self.text(205, y, value, 14, True)
        self.line(18, y+12, 342, y+12)

    def box(self, y, heading, lines, h=None):
        h = h or 48+len(lines)*23
        self.rect(18, y, 324, h, '#f2f2f2', '#aaa', 5)
        self.text(30, y+27, heading, 15, True)
        for i, line in enumerate(lines):
            self.text(30, y+51+i*23, line, 13)

    def footer(self, label='← На карту', target='01-map'):
        self.button(696, label, target)

    def map(self, x, y, w, h):
        self.rect(x, y, w, h, '#f3f3f3', '#aaa')
        self.line(x, y+h*.7, x+w, y+h*.2)
        self.line(x+w*.3, y, x+w*.75, y+h)
        fills = ['#e8e8e8', '#d5d5d5', '#b7b7b7', '#fff']
        labels = ['З', 'Ж', 'К', 'Н/Д']
        size = 48
        for r in range(1 if h < 200 else 3):
            for c in range(4):
                idx = (r+c)%4
                xx, yy = x+40+c*size, y+54+r*size
                self.parts.append('<a href="#03-card" aria-label="Открыть карточку ячейки">')
                self.rect(xx, yy, size, size, fills[idx], '#777')
                self.text(xx+10, yy+29, labels[idx], 12, True)
                self.parts.append('</a>')
        self.text(x+12, y+24, 'Подложка Яндекс Карт · схема', 12)
        self.text(x+12, y+h-13, 'Ячейка 250 × 250 м', 12)

    def svg(self):
        return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.width} {self.height}" width="{self.width}" height="{self.height}" role="img" aria-label="{escape(self.title)}" font-family="Arial, sans-serif">'+''.join(self.parts)+'</svg>'


